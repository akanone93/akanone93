import 'package:flutter_test/flutter_test.dart';

/// Asserts Flutter's accessibility guidelines on the page now pumped
/// (QA-011): tap targets of 48 x 48 on Android and 44 x 44 on iOS, a label
/// on every tappable node, and text contrast.
Future<void> expectMeetsA11yGuidelines(WidgetTester tester) async {
  final handle = tester.ensureSemantics();
  try {
    await expectLater(tester, meetsGuideline(androidTapTargetGuideline));
    await expectLater(tester, meetsGuideline(iOSTapTargetGuideline));
    await expectLater(tester, meetsGuideline(labeledTapTargetGuideline));
    await expectLater(tester, meetsGuideline(textContrastGuideline));
  } finally {
    handle.dispose();
  }
}
