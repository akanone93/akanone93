// Command gen writes the permission catalogue and the predefined roles of
// package auth, and their reference table, from permissions.json and
// roles.json (go:generate in package auth; ADR-0073, GOV-002). The JSON
// files are the single source: the Go tables, docs/reference/permissions.md
// and Studio's typed catalogue (@plux/schema) follow them, and nothing else lists a permission or a role's grants.
package main

import (
	"bytes"
	"cmp"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strings"
)

type permission struct {
	Name        string `json:"name"`
	Description string `json:"description"`
	Area        string `json:"area"`
	Feature     string `json:"feature"`
	Action      string `json:"action"`
	Risk        string `json:"risk"`
	StepUp      bool   `json:"stepUp"`
	Scope       string `json:"scope"`
	ReadOnly    bool   `json:"readOnly"`
}

type role struct {
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Permissions []string `json:"permissions"`
}

var (
	namePattern = regexp.MustCompile(`^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+$`)
	rolePattern = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)
	risks       = []string{"low", "medium", "high"}
	scopes      = []string{"organization", "app", "environment"}
)

const (
	goHeader = "// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: AGPL-3.0-only\n\n" +
		"// Code generated by internal/gen from permissions.json and roles.json (go generate). DO NOT EDIT.\n\npackage auth\n\n"
	tsHeader = "// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: AGPL-3.0-only\n\n" +
		"// Code generated by internal/gen from permissions.json and roles.json (go generate). DO NOT EDIT.\n\n"
	// tsWidth is the line width Biome formats Studio's TypeScript to.
	tsWidth   = 120
	docHeader = "<!-- Code generated by backend/internal/auth (go generate). DO NOT EDIT. -->\n\n"
)

func main() {
	if len(os.Args) != 6 {
		fmt.Fprintln(os.Stderr, "usage: gen <permissions.json> <roles.json> <catalogue_gen.go> <permissions.md> <permissions.gen.ts>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2], os.Args[3], os.Args[4], os.Args[5]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(2)
	}
}

func read(path string, v any) error {
	b, err := os.ReadFile(path) //nolint:gosec // G304: the developer names the input.
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

func run(permsPath, rolesPath, goOut, docOut, tsOut string) error {
	var pf struct {
		Permissions []permission `json:"permissions"`
	}
	var rf struct {
		Roles []role `json:"roles"`
	}
	if err := read(permsPath, &pf); err != nil {
		return err
	}
	if err := read(rolesPath, &rf); err != nil {
		return err
	}
	if err := check(pf.Permissions, rf.Roles); err != nil {
		return err
	}
	src, err := format.Source([]byte(renderGo(pf.Permissions, rf.Roles)))
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	if err := os.WriteFile(goOut, src, 0o644); err != nil { //nolint:gosec // G306: a source file.
		return fmt.Errorf("write %s: %w", goOut, err)
	}
	if err := os.WriteFile(docOut, []byte(renderDoc(pf.Permissions, rf.Roles)), 0o644); err != nil { //nolint:gosec // G306: a document.
		return fmt.Errorf("write %s: %w", docOut, err)
	}
	if err := os.WriteFile(tsOut, []byte(renderTS(pf.Permissions, rf.Roles)), 0o644); err != nil { //nolint:gosec // G306: a source file.
		return fmt.Errorf("write %s: %w", tsOut, err)
	}
	return nil
}

// check refuses a catalogue the Go code could not rely on.
func check(perms []permission, roles []role) error {
	known := map[string]bool{}
	for i, p := range perms {
		switch {
		case !namePattern.MatchString(p.Name):
			return fmt.Errorf("permission %q is not a dotted lower-case name", p.Name)
		case i > 0 && perms[i-1].Name >= p.Name:
			return fmt.Errorf("permission %q is out of order or repeated; keep the file sorted", p.Name)
		case strings.TrimSpace(p.Description) == "":
			return fmt.Errorf("permission %q has no description", p.Name)
		case !groupedCorrectly(p):
			return fmt.Errorf("permission %q: area %q, feature %q and action %q must spell the name as <area>.<action> or <area>.<feature>.<action>", p.Name, p.Area, p.Feature, p.Action)
		case !slices.Contains(risks, p.Risk):
			return fmt.Errorf("permission %q: risk %q is not low, medium or high", p.Name, p.Risk)
		case !slices.Contains(scopes, p.Scope):
			return fmt.Errorf("permission %q: scope %q is not organization, app or environment", p.Name, p.Scope)
		}
		known[p.Name] = true
	}
	seen := map[string]bool{}
	for _, r := range roles {
		switch {
		case !rolePattern.MatchString(r.Name):
			return fmt.Errorf("role %q is not a lower-case name", r.Name)
		case seen[r.Name]:
			return fmt.Errorf("role %q is repeated", r.Name)
		case strings.TrimSpace(r.Description) == "":
			return fmt.Errorf("role %q has no description", r.Name)
		}
		seen[r.Name] = true
		for i, p := range r.Permissions {
			switch {
			case p == "*" && len(r.Permissions) == 1:
			case !known[p]:
				return fmt.Errorf("role %q grants %q, which is not in the catalogue", r.Name, p)
			case i > 0 && r.Permissions[i-1] >= p:
				return fmt.Errorf("role %q: %q is out of order or repeated", r.Name, p)
			}
		}
	}
	return nil
}

// groupedCorrectly reports whether a permission's area, feature and action
// are present and spell its name, so the grouping and the name cannot
// disagree (GOV-002).
func groupedCorrectly(p permission) bool {
	if p.Area == "" || p.Feature == "" || p.Action == "" {
		return false
	}
	return p.Name == p.Area+"."+p.Action || p.Name == p.Area+"."+p.Feature+"."+p.Action
}

// expand returns a role's permissions, with "*" meaning the whole catalogue.
func expand(r role, perms []permission) []string {
	if len(r.Permissions) == 1 && r.Permissions[0] == "*" {
		out := make([]string, len(perms))
		for i, p := range perms {
			out[i] = p.Name
		}
		return out
	}
	return r.Permissions
}

func renderGo(perms []permission, roles []role) string {
	var b strings.Builder
	b.WriteString(goHeader)
	b.WriteString("// catalogue is the permission catalogue, sorted by name.\nvar catalogue = []PermissionInfo{\n")
	for _, p := range perms {
		fmt.Fprintf(&b, "\t{Name: %q, Description: %q, Area: %q, Feature: %q, Action: %q, Risk: %s, StepUp: %t, Scope: %s, ReadOnly: %t},\n",
			p.Name, p.Description, p.Area, p.Feature, p.Action, goRisk(p.Risk), p.StepUp, goScope(p.Scope), p.ReadOnly)
	}
	b.WriteString("}\n\n// predefined are the predefined roles, in the order the specification lists them.\nvar predefined = []RoleInfo{\n")
	for _, r := range roles {
		fmt.Fprintf(&b, "\t{Name: %q, Description: %q},\n", r.Name, r.Description)
	}
	b.WriteString("}\n\n// grants maps each predefined role to the permissions it holds. A role holds\n// exactly what is listed: there is no inheritance to reason about.\nvar grants = map[Role][]Permission{\n")
	for _, r := range roles {
		fmt.Fprintf(&b, "\t%q: {", r.Name)
		for i, p := range expand(r, perms) {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", p)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func goRisk(s string) string {
	return "Risk" + strings.ToUpper(s[:1]) + s[1:]
}

func goScope(s string) string {
	return "Scope" + strings.ToUpper(s[:1]) + s[1:]
}

func renderDoc(perms []permission, roles []role) string {
	var b strings.Builder
	b.WriteString(docHeader)
	b.WriteString("# Permissions and roles\n\n")
	b.WriteString("Every call to the Plux Server names the permission it needs, and a principal that does not hold it is refused (`SEC-102`). ")
	b.WriteString("This page lists the permission catalogue and the predefined roles (`GOV-002`, [ADR-0073](../adr/0073-roles-permissions-and-scoping.md)). ")
	b.WriteString("It is generated from `backend/internal/auth/permissions.json` and `backend/internal/auth/roles.json`.\n\n")
	b.WriteString("## Permissions\n\n")
	b.WriteString("**Risk** is the damage a misused permission can do. **Step-up** permissions are usable only in a session that presented a second factor (`SEC-100`, `SEC-103`). ")
	b.WriteString("**Scope** is the narrowest scope a permission can be granted at: `organization` permissions apply across the organisation only; `app` permissions can also be granted on one app; ")
	b.WriteString("`environment` permissions can also be granted on one environment of an app and written `<permission>:<environment>`, for example `release.publish:production` (`GOV-003`). ")
	b.WriteString("**Read-only** permissions change nothing.\n\n")
	b.WriteString("The catalogue is grouped as area, feature, action (`GOV-002`). A restriction policy names a permission or one of the wildcards `*`, `<area>.*` and `<area>.<feature>.*` (`GOV-006`, [ADR-0086](../adr/0086-restriction-policies-and-effective-permissions.md)).\n\n")
	renderGroups(&b, perms)
	b.WriteString("\n## Predefined roles\n\n")
	for _, r := range roles {
		fmt.Fprintf(&b, "- **%s** — %s\n", r.Name, r.Description)
	}
	b.WriteString("\nA role holds exactly the permissions marked below; there is no inheritance.\n\n")
	b.WriteString("| Permission |")
	for _, r := range roles {
		fmt.Fprintf(&b, " %s |", r.Name)
	}
	b.WriteString("\n|---|")
	for range roles {
		b.WriteString(":-:|")
	}
	b.WriteString("\n")
	held := make([]map[string]bool, len(roles))
	for i, r := range roles {
		held[i] = map[string]bool{}
		for _, p := range expand(r, perms) {
			held[i][p] = true
		}
	}
	for _, p := range perms {
		fmt.Fprintf(&b, "| `%s` |", p.Name)
		for i := range roles {
			if held[i][p.Name] {
				b.WriteString(" ✓ |")
			} else {
				b.WriteString("  |")
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}

// renderGroups writes the permission table grouped by area, then feature,
// each group with its own heading.
func renderGroups(b *strings.Builder, perms []permission) {
	sorted := slices.Clone(perms)
	slices.SortStableFunc(sorted, func(x, y permission) int {
		return cmp.Or(strings.Compare(x.Area, y.Area), strings.Compare(x.Feature, y.Feature))
	})
	for i, p := range sorted {
		newArea := i == 0 || p.Area != sorted[i-1].Area
		if newArea {
			fmt.Fprintf(b, "### Area `%s`\n\n", p.Area)
		}
		if newArea || p.Feature != sorted[i-1].Feature {
			fmt.Fprintf(b, "#### Feature `%s`\n\n", p.Feature)
			b.WriteString("| Permission | Action | Description | Risk | Step-up | Scope | Read-only |\n|---|---|---|---|---|---|---|\n")
		}
		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s | %s | %s | %s |\n", p.Name, p.Action, p.Description, p.Risk, yes(p.StepUp), p.Scope, yes(p.ReadOnly))
		if i+1 == len(sorted) || sorted[i+1].Area != p.Area || sorted[i+1].Feature != p.Feature {
			b.WriteString("\n")
		}
	}
}

func yes(v bool) string {
	if v {
		return "yes"
	}
	return ""
}

// tsString quotes s as a TypeScript string literal.
func tsString(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		panic(err) // A string always encodes.
	}
	return strings.TrimSuffix(b.String(), "\n")
}

// tsUnion writes `export type <name> = "a" | "b";`, one member per line when
// it does not fit the line width, as the formatter would.
func tsUnion(b *strings.Builder, doc, name string, members []string) {
	quoted := make([]string, len(members))
	for i, m := range members {
		quoted[i] = tsString(m)
	}
	fmt.Fprintf(b, "/** %s */\n", doc)
	oneLine := "export type " + name + " = " + strings.Join(quoted, " | ") + ";"
	if len(oneLine) <= tsWidth {
		b.WriteString(oneLine + "\n\n")
		return
	}
	b.WriteString("export type " + name + " =\n")
	for i, q := range quoted {
		end := "\n"
		if i == len(quoted)-1 {
			end = ";\n"
		}
		b.WriteString("  | " + q + end)
	}
	b.WriteString("\n")
}

// tsList writes a string-array property at the given indent, wrapped one
// element per line when it does not fit the line width.
func tsList(b *strings.Builder, indent, key string, items []string) {
	quoted := make([]string, len(items))
	for i, it := range items {
		quoted[i] = tsString(it)
	}
	oneLine := indent + key + ": [" + strings.Join(quoted, ", ") + "],"
	if len(oneLine) <= tsWidth {
		b.WriteString(oneLine + "\n")
		return
	}
	b.WriteString(indent + key + ": [\n")
	for _, q := range quoted {
		b.WriteString(indent + "  " + q + ",\n")
	}
	b.WriteString(indent + "],\n")
}

// distinct returns the values of f over perms, sorted and without repeats.
func distinct(perms []permission, f func(permission) string) []string {
	var out []string
	for _, p := range perms {
		out = append(out, f(p))
	}
	slices.Sort(out)
	return slices.Compact(out)
}

// renderTS writes the catalogue as TypeScript for @plux/schema, already in
// the shape Biome formats it to, so a formatter run leaves it unchanged. A
// role holding "*" lists every permission, as the Go table does.
func renderTS(perms []permission, roles []role) string {
	var b strings.Builder
	b.WriteString(tsHeader)
	names := make([]string, len(perms))
	for i, p := range perms {
		names[i] = p.Name
	}
	tsUnion(&b, "Every permission name in the server's catalogue (GOV-002).", "PermissionName", names)
	tsUnion(&b, "How much damage a misused permission can do.", "PermissionRisk", distinct(perms, func(p permission) string { return p.Risk }))
	tsUnion(&b, "The narrowest scope a permission can be granted at (GOV-003).", "PermissionScope", distinct(perms, func(p permission) string { return p.Scope }))
	b.WriteString(`/** One entry of the permission catalogue (GOV-002). */
export interface PermissionDefinition {
  readonly name: PermissionName;
  readonly description: string;
  readonly area: string;
  readonly feature: string;
  readonly action: string;
  readonly risk: PermissionRisk;
  readonly stepUp: boolean;
  readonly scope: PermissionScope;
  readonly readOnly: boolean;
}

/** The permission catalogue, in name order. */
export const permissions = [
`)
	for _, p := range perms {
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    name: %s,\n    description: %s,\n    area: %s,\n    feature: %s,\n    action: %s,\n",
			tsString(p.Name), tsString(p.Description), tsString(p.Area), tsString(p.Feature), tsString(p.Action))
		fmt.Fprintf(&b, "    risk: %s,\n    stepUp: %t,\n    scope: %s,\n    readOnly: %t,\n  },\n", tsString(p.Risk), p.StepUp, tsString(p.Scope), p.ReadOnly)
	}
	b.WriteString("] as const satisfies readonly PermissionDefinition[];\n\n")
	roleNames := make([]string, len(roles))
	for i, r := range roles {
		roleNames[i] = r.Name
	}
	tsUnion(&b, "The predefined roles (GOV-002).", "RoleName", roleNames)
	b.WriteString(`/** One predefined role and the permissions it holds. */
export interface RoleDefinition {
  readonly name: RoleName;
  readonly description: string;
  readonly permissions: readonly PermissionName[];
}

/** The predefined roles, in the order the specification lists them. */
export const roles = [
`)
	for _, r := range roles {
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    name: %s,\n    description: %s,\n", tsString(r.Name), tsString(r.Description))
		tsList(&b, "    ", "permissions", expand(r, perms))
		b.WriteString("  },\n")
	}
	b.WriteString("] as const satisfies readonly RoleDefinition[];\n")
	return b.String()
}
