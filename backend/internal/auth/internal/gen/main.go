// Command gen writes the permission catalogue and the predefined roles of
// package auth, and their reference table, from permissions.json and
// roles.json (go:generate in package auth; ADR-0073, GOV-002). The JSON
// files are the single source: the Go tables and docs/reference/permissions.md
// follow them, and nothing else lists a permission or a role's grants.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strings"
)

type permission struct {
	Name        string `json:"name"`
	Description string `json:"description"`
	Risk        string `json:"risk"`
	StepUp      bool   `json:"stepUp"`
	Scope       string `json:"scope"`
	ReadOnly    bool   `json:"readOnly"`
}

type role struct {
	Name        string   `json:"name"`
	Description string   `json:"description"`
	Permissions []string `json:"permissions"`
}

var (
	namePattern = regexp.MustCompile(`^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+$`)
	rolePattern = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)
	risks       = []string{"low", "medium", "high"}
	scopes      = []string{"organization", "app", "environment"}
)

const (
	goHeader = "// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: AGPL-3.0-only\n\n" +
		"// Code generated by internal/gen from permissions.json and roles.json (go generate). DO NOT EDIT.\n\npackage auth\n\n"
	docHeader = "<!-- Code generated by backend/internal/auth (go generate). DO NOT EDIT. -->\n\n"
)

func main() {
	if len(os.Args) != 5 {
		fmt.Fprintln(os.Stderr, "usage: gen <permissions.json> <roles.json> <catalogue_gen.go> <permissions.md>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2], os.Args[3], os.Args[4]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(2)
	}
}

func read(path string, v any) error {
	b, err := os.ReadFile(path) //nolint:gosec // G304: the developer names the input.
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

func run(permsPath, rolesPath, goOut, docOut string) error {
	var pf struct {
		Permissions []permission `json:"permissions"`
	}
	var rf struct {
		Roles []role `json:"roles"`
	}
	if err := read(permsPath, &pf); err != nil {
		return err
	}
	if err := read(rolesPath, &rf); err != nil {
		return err
	}
	if err := check(pf.Permissions, rf.Roles); err != nil {
		return err
	}
	src, err := format.Source([]byte(renderGo(pf.Permissions, rf.Roles)))
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	if err := os.WriteFile(goOut, src, 0o644); err != nil { //nolint:gosec // G306: a source file.
		return fmt.Errorf("write %s: %w", goOut, err)
	}
	if err := os.WriteFile(docOut, []byte(renderDoc(pf.Permissions, rf.Roles)), 0o644); err != nil { //nolint:gosec // G306: a document.
		return fmt.Errorf("write %s: %w", docOut, err)
	}
	return nil
}

// check refuses a catalogue the Go code could not rely on.
func check(perms []permission, roles []role) error {
	known := map[string]bool{}
	for i, p := range perms {
		switch {
		case !namePattern.MatchString(p.Name):
			return fmt.Errorf("permission %q is not a dotted lower-case name", p.Name)
		case i > 0 && perms[i-1].Name >= p.Name:
			return fmt.Errorf("permission %q is out of order or repeated; keep the file sorted", p.Name)
		case strings.TrimSpace(p.Description) == "":
			return fmt.Errorf("permission %q has no description", p.Name)
		case !slices.Contains(risks, p.Risk):
			return fmt.Errorf("permission %q: risk %q is not low, medium or high", p.Name, p.Risk)
		case !slices.Contains(scopes, p.Scope):
			return fmt.Errorf("permission %q: scope %q is not organization, app or environment", p.Name, p.Scope)
		}
		known[p.Name] = true
	}
	seen := map[string]bool{}
	for _, r := range roles {
		switch {
		case !rolePattern.MatchString(r.Name):
			return fmt.Errorf("role %q is not a lower-case name", r.Name)
		case seen[r.Name]:
			return fmt.Errorf("role %q is repeated", r.Name)
		case strings.TrimSpace(r.Description) == "":
			return fmt.Errorf("role %q has no description", r.Name)
		}
		seen[r.Name] = true
		for i, p := range r.Permissions {
			switch {
			case p == "*" && len(r.Permissions) == 1:
			case !known[p]:
				return fmt.Errorf("role %q grants %q, which is not in the catalogue", r.Name, p)
			case i > 0 && r.Permissions[i-1] >= p:
				return fmt.Errorf("role %q: %q is out of order or repeated", r.Name, p)
			}
		}
	}
	return nil
}

// expand returns a role's permissions, with "*" meaning the whole catalogue.
func expand(r role, perms []permission) []string {
	if len(r.Permissions) == 1 && r.Permissions[0] == "*" {
		out := make([]string, len(perms))
		for i, p := range perms {
			out[i] = p.Name
		}
		return out
	}
	return r.Permissions
}

func renderGo(perms []permission, roles []role) string {
	var b strings.Builder
	b.WriteString(goHeader)
	b.WriteString("// catalogue is the permission catalogue, sorted by name.\nvar catalogue = []PermissionInfo{\n")
	for _, p := range perms {
		fmt.Fprintf(&b, "\t{Name: %q, Description: %q, Risk: %s, StepUp: %t, Scope: %s, ReadOnly: %t},\n",
			p.Name, p.Description, goRisk(p.Risk), p.StepUp, goScope(p.Scope), p.ReadOnly)
	}
	b.WriteString("}\n\n// predefined are the predefined roles, in the order the specification lists them.\nvar predefined = []RoleInfo{\n")
	for _, r := range roles {
		fmt.Fprintf(&b, "\t{Name: %q, Description: %q},\n", r.Name, r.Description)
	}
	b.WriteString("}\n\n// grants maps each predefined role to the permissions it holds. A role holds\n// exactly what is listed: there is no inheritance to reason about.\nvar grants = map[Role][]Permission{\n")
	for _, r := range roles {
		fmt.Fprintf(&b, "\t%q: {", r.Name)
		for i, p := range expand(r, perms) {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", p)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func goRisk(s string) string {
	return "Risk" + strings.ToUpper(s[:1]) + s[1:]
}

func goScope(s string) string {
	return "Scope" + strings.ToUpper(s[:1]) + s[1:]
}

func renderDoc(perms []permission, roles []role) string {
	var b strings.Builder
	b.WriteString(docHeader)
	b.WriteString("# Permissions and roles\n\n")
	b.WriteString("Every call to the Plux Server names the permission it needs, and a principal that does not hold it is refused (`SEC-102`). ")
	b.WriteString("This page lists the permission catalogue and the predefined roles (`GOV-002`, [ADR-0073](../adr/0073-roles-permissions-and-scoping.md)). ")
	b.WriteString("It is generated from `backend/internal/auth/permissions.json` and `backend/internal/auth/roles.json`.\n\n")
	b.WriteString("## Permissions\n\n")
	b.WriteString("**Risk** is the damage a misused permission can do. **Step-up** permissions are usable only in a session that presented a second factor (`SEC-100`, `SEC-103`). ")
	b.WriteString("**Scope** is the narrowest scope a permission can be granted at: `organization` permissions apply across the organisation only; `app` permissions can also be granted on one app; ")
	b.WriteString("`environment` permissions can also be granted on one environment of an app and written `<permission>:<environment>`, for example `release.publish:production` (`GOV-003`). ")
	b.WriteString("**Read-only** permissions change nothing.\n\n")
	b.WriteString("| Permission | Description | Risk | Step-up | Scope | Read-only |\n|---|---|---|---|---|---|\n")
	for _, p := range perms {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", p.Name, p.Description, p.Risk, yes(p.StepUp), p.Scope, yes(p.ReadOnly))
	}
	b.WriteString("\n## Predefined roles\n\n")
	for _, r := range roles {
		fmt.Fprintf(&b, "- **%s** — %s\n", r.Name, r.Description)
	}
	b.WriteString("\nA role holds exactly the permissions marked below; there is no inheritance.\n\n")
	b.WriteString("| Permission |")
	for _, r := range roles {
		fmt.Fprintf(&b, " %s |", r.Name)
	}
	b.WriteString("\n|---|")
	for range roles {
		b.WriteString(":-:|")
	}
	b.WriteString("\n")
	held := make([]map[string]bool, len(roles))
	for i, r := range roles {
		held[i] = map[string]bool{}
		for _, p := range expand(r, perms) {
			held[i][p] = true
		}
	}
	for _, p := range perms {
		fmt.Fprintf(&b, "| `%s` |", p.Name)
		for i := range roles {
			if held[i][p.Name] {
				b.WriteString(" ✓ |")
			} else {
				b.WriteString("  |")
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}

func yes(v bool) string {
	if v {
		return "yes"
	}
	return ""
}
