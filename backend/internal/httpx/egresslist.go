package httpx

import (
	"fmt"
	"strings"
)

// egressListHeader opens docs/operations/egress.md.
const egressListHeader = `<!-- Code generated by backend/internal/httpx (go generate). DO NOT EDIT. -->

# Egress list

By default no data leaves a self-hosted installation except calls the customer configures (` + "`SEC-163`" + `). This page lists every kind of outbound connection the Plux Server can make. It is generated from the registry of destinations in ` + "`backend/internal/httpx/destinations.go`" + `, and a test fails when it differs: a new outbound call cannot ship without an entry here.

Every outbound connection is built for one of these kinds. A kind with fixed hosts refuses any other host when it connects. A kind without fixed hosts goes to an address the customer enters, and the SSRF policy refuses private, loopback, link-local and metadata addresses unless the installation allows them (` + "`SEC-104`, `SEC-105`" + `).

`

// RenderEgressList returns the Markdown of docs/operations/egress.md for
// the registry (SEC-163).
func RenderEgressList() string {
	var b strings.Builder
	b.WriteString(egressListHeader)
	b.WriteString("| Destination | Purpose | Configured by | Hosts | Default | Data sent |\n|---|---|---|---|---|---|\n")
	for _, d := range registry {
		fmt.Fprintf(&b, "| %s (`%s`) | %s | %s: %s | %s | %s | %s |\n",
			d.Name, d.Kind, d.Purpose, d.ConfiguredBy, d.Setting, hostsCell(d), d.Default, d.Data)
	}
	b.WriteString("\n## Not egress\n\nThe installation also connects to services its operator runs and names. Nothing reaches a third party through them:\n\n")
	for _, item := range infrastructure {
		fmt.Fprintf(&b, "- %s\n", item)
	}
	return b.String()
}

// hostsCell renders the hosts of a destination for the table.
func hostsCell(d Destination) string {
	if !d.FixedHosts() {
		return "the address the customer enters"
	}
	hosts := make([]string, len(d.Hosts))
	for i, h := range d.Hosts {
		hosts[i] = "`" + h + "`"
	}
	return strings.Join(hosts, ", ")
}
