// Command gen writes the calendar tables of package calendar and of the Dart
// runtime from schema/l10n/calendars/umalqura.json and persian.json
// (go:generate in package calendar; ADR-0067). The JSON files are the single
// source; this command never reads ICU.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

type umalqura struct {
	YearStart     int   `json:"yearStart"`
	YearEnd       int   `json:"yearEnd"`
	CivilEpochJDN int   `json:"civilEpochJdn"`
	EpochDay1300  int   `json:"epochDay1300"`
	MonthMasks    []int `json:"monthMasks"`
}

type persian struct {
	EpochJDN     int   `json:"epochJdn"`
	NonLeapYears []int `json:"nonLeapYears"`
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen <calendars dir> <tables_gen.go> <tables.g.dart>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2], os.Args[3]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(2)
	}
}

func read(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(b, v); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

func run(dir, goOut, dartOut string) error {
	var u umalqura
	var p persian
	if err := read(filepath.Join(dir, "umalqura.json"), &u); err != nil {
		return err
	}
	if err := read(filepath.Join(dir, "persian.json"), &p); err != nil {
		return err
	}
	if len(u.MonthMasks) != u.YearEnd-u.YearStart+1 {
		return fmt.Errorf("umalqura.json: %d masks for %d..%d", len(u.MonthMasks), u.YearStart, u.YearEnd)
	}
	// starts[i] is the first day of year yearStart+i, in days after the
	// civil epoch; the last entry is the day after the table.
	starts := make([]int, 0, len(u.MonthMasks)+1)
	day := u.EpochDay1300
	for _, m := range u.MonthMasks {
		starts = append(starts, day)
		for i := 0; i < 12; i++ {
			day += 29 + (m>>(11-i))&1
		}
	}
	starts = append(starts, day)

	var g bytes.Buffer
	g.WriteString("// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: Apache-2.0\n\n")
	g.WriteString("// Code generated by internal/gen from schema/l10n/calendars. DO NOT EDIT.\n\npackage calendar\n\n")
	fmt.Fprintf(&g, "const (\n umalquraYearStart = %d\n umalquraYearEnd = %d\n civilEpochJDN = %d\n persianEpochJDN = %d\n)\n\n",
		u.YearStart, u.YearEnd, u.CivilEpochJDN, p.EpochJDN)
	g.WriteString("// umalquraMonthMasks holds, per year from umalquraYearStart, a bit per month\n// (bit 11-m for month m, 0-based) that is set when the month has 30 days.\n")
	g.WriteString("var umalquraMonthMasks = [...]uint16{" + list(u.MonthMasks, "0x%04X", " ") + "}\n\n")
	g.WriteString("// umalquraYearStarts holds the first day of each year, in days after the civil\n// epoch, and the day after the last table year.\n")
	g.WriteString("var umalquraYearStarts = [...]int32{" + list(starts, "%d", " ") + "}\n\n")
	g.WriteString("// persianNonLeapYears are the years ICU corrects to non-leap, ascending.\n")
	g.WriteString("var persianNonLeapYears = [...]int32{" + list(p.NonLeapYears, "%d", " ") + "}\n")
	src, err := format.Source(g.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile(goOut, src, 0o644); err != nil {
		return err
	}

	var d bytes.Buffer
	d.WriteString("// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: Apache-2.0\n\n")
	d.WriteString("// Code generated by backend/internal/l10n/calendar/internal/gen from\n// schema/l10n/calendars. DO NOT EDIT.\n\n")
	d.WriteString("/// Calendar tables pinned from ICU (ADR-0067).\nlibrary;\n\n")
	fmt.Fprintf(&d, "/// The first Umm al-Qura table year.\nconst int umalquraYearStart = %d;\n\n", u.YearStart)
	fmt.Fprintf(&d, "/// The last Umm al-Qura table year.\nconst int umalquraYearEnd = %d;\n\n", u.YearEnd)
	fmt.Fprintf(&d, "/// The Julian day number of the Islamic civil epoch.\nconst int civilEpochJdn = %d;\n\n", u.CivilEpochJDN)
	fmt.Fprintf(&d, "/// The Julian day number of the Persian epoch.\nconst int persianEpochJdn = %d;\n\n", p.EpochJDN)
	d.WriteString("/// Per Umm al-Qura year, a bit per month (bit 11-m) set when it has 30 days.\n")
	d.WriteString("const List<int> umalquraMonthMasks = [" + list(u.MonthMasks, "0x%04X", "  ") + "];\n\n")
	d.WriteString("/// The first day of each Umm al-Qura year in days after the civil epoch, then\n/// the day after the table.\n")
	d.WriteString("const List<int> umalquraYearStarts = [" + list(starts, "%d", "  ") + "];\n\n")
	d.WriteString("/// The Persian years ICU corrects to non-leap, ascending.\n")
	d.WriteString("const List<int> persianNonLeapYears = [" + list(p.NonLeapYears, "%d", "  ") + "];\n")
	return os.WriteFile(dartOut, d.Bytes(), 0o644)
}

// list formats ints eight to a line, indented, each followed by a comma.
func list(v []int, f, indent string) string {
	var b strings.Builder
	b.WriteString("\n")
	for i, x := range v {
		if i%8 == 0 {
			b.WriteString(indent)
		}
		fmt.Fprintf(&b, f+",", x)
		if i%8 == 7 || i == len(v)-1 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	return b.String()
}
