// Command gen writes the network profile tables of package netsim and of
// the Dart runtime from schema/devtools/network-profiles.json
// (go:generate in package netsim; DEV-031). The JSON file is the single
// source: the profiles are defined once and nothing else lists them.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strconv"
	"strings"
)

type profile struct {
	ID                string  `json:"id"`
	Description       string  `json:"description"`
	LatencyMs         int64   `json:"latencyMs"`
	JitterMs          int64   `json:"jitterMs"`
	DownKbitPerSecond int64   `json:"downKbitPerSecond"`
	UpKbitPerSecond   int64   `json:"upKbitPerSecond"`
	LossPercent       float64 `json:"lossPercent"`
}

type registry struct {
	Profiles []profile `json:"profiles"`
}

var idPattern = regexp.MustCompile(`^[a-z0-9]+(_[a-z0-9]+)*$`)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen <network-profiles.json> <profiles_gen.go> <network_profiles.g.dart>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2], os.Args[3]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(2)
	}
}

func load(path string) ([]profile, error) {
	b, err := os.ReadFile(path) //nolint:gosec // G304: the developer names the input.
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	var raw struct {
		registry
		Schema  string `json:"$schema"`
		Comment string `json:"$comment"`
	}
	if err := dec.Decode(&raw); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(raw.Profiles) == 0 {
		return nil, fmt.Errorf("%s: no profiles", path)
	}
	seen := map[string]bool{}
	for _, p := range raw.Profiles {
		switch {
		case !idPattern.MatchString(p.ID):
			return nil, fmt.Errorf("%s: invalid id %q", path, p.ID)
		case seen[p.ID]:
			return nil, fmt.Errorf("%s: duplicate id %q", path, p.ID)
		case p.Description == "":
			return nil, fmt.Errorf("%s: %s has no description", path, p.ID)
		case p.LatencyMs < 0 || p.JitterMs < 0 || p.DownKbitPerSecond < 0 || p.UpKbitPerSecond < 0:
			return nil, fmt.Errorf("%s: %s has a negative value", path, p.ID)
		case p.LossPercent < 0 || p.LossPercent > 100:
			return nil, fmt.Errorf("%s: %s has loss %v outside 0..100", path, p.ID, p.LossPercent)
		}
		seen[p.ID] = true
	}
	return raw.Profiles, nil
}

func run(in, goOut, dartOut string) error {
	profiles, err := load(in)
	if err != nil {
		return err
	}

	var g bytes.Buffer
	g.WriteString("// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: AGPL-3.0-only\n\n")
	g.WriteString("// Code generated by internal/gen from schema/devtools/network-profiles.json. DO NOT EDIT.\n\npackage netsim\n\nimport \"time\"\n\n")
	g.WriteString("// DevProfiles are the network profiles of dev sessions (DEV-031), in the\n// order of the registry.\nvar DevProfiles = [...]DevProfile{\n")
	for _, p := range profiles {
		fmt.Fprintf(&g, "\t{\n\t\tID: %q,\n\t\tDescription: %q,\n\t\tJitter: %d * time.Millisecond,\n", p.ID, p.Description, p.JitterMs)
		fmt.Fprintf(&g, "\t\tProfile: Profile{Down: %d, Up: %d, RTT: %d * time.Millisecond, Loss: %s, MSS: defaultMSS},\n\t},\n",
			p.DownKbitPerSecond*1000, p.UpKbitPerSecond*1000, p.LatencyMs, strconv.FormatFloat(p.LossPercent/100, 'g', -1, 64))
	}
	g.WriteString("}\n")
	src, err := format.Source(g.Bytes())
	if err != nil {
		return fmt.Errorf("format Go table: %w", err)
	}
	if err := os.WriteFile(goOut, src, 0o600); err != nil { //nolint:gosec // G703: the developer names the output.
		return fmt.Errorf("write %s: %w", goOut, err)
	}

	var d strings.Builder
	d.WriteString("// SPDX-FileCopyrightText: 2026 Plux contributors\n// SPDX-License-Identifier: Apache-2.0\n\n")
	d.WriteString("// Code generated by backend/internal/netsim/internal/gen from\n// schema/devtools/network-profiles.json. DO NOT EDIT.\n\n")
	d.WriteString("/// The network profiles of dev sessions (DEV-031).\nlibrary;\n\n")
	d.WriteString("/// A network profile a dev session can apply to the runtime's HTTP client.\n")
	d.WriteString("final class NetworkProfile {\n  /// Creates a profile.\n  const NetworkProfile({\n    required this.id,\n    required this.description,\n    required this.latencyMs,\n    required this.jitterMs,\n    required this.downKbitPerSecond,\n    required this.upKbitPerSecond,\n    required this.lossPercent,\n  });\n\n")
	d.WriteString("  /// The stable identifier, such as `3g`.\n  final String id;\n\n")
	d.WriteString("  /// What the profile stands for.\n  final String description;\n\n")
	d.WriteString("  /// The added round-trip time, in milliseconds.\n  final int latencyMs;\n\n")
	d.WriteString("  /// The random variation of the latency, in milliseconds, either way.\n  final int jitterMs;\n\n")
	d.WriteString("  /// The download bandwidth, in kbit/s.\n  final int downKbitPerSecond;\n\n")
	d.WriteString("  /// The upload bandwidth, in kbit/s.\n  final int upKbitPerSecond;\n\n")
	d.WriteString("  /// The packet loss, in percent; 100 drops everything.\n  final double lossPercent;\n}\n\n")
	d.WriteString("/// Every profile, in the order of the registry.\nconst List<NetworkProfile> networkProfiles = [\n")
	for _, p := range profiles {
		desc := "    description: " + dartString(p.Description) + ","
		// dart format moves a value that does not fit to its own line, when
		// it fits there.
		if wrapped := "    description:\n        " + dartString(p.Description) + ","; len(desc) > 80 && len(wrapped)-len("    description:\n") <= 80 {
			desc = wrapped
		}
		fmt.Fprintf(&d, "  NetworkProfile(\n    id: %s,\n%s\n    latencyMs: %d,\n    jitterMs: %d,\n    downKbitPerSecond: %d,\n    upKbitPerSecond: %d,\n    lossPercent: %s,\n  ),\n",
			dartString(p.ID), desc, p.LatencyMs, p.JitterMs, p.DownKbitPerSecond, p.UpKbitPerSecond, dartDouble(p.LossPercent))
	}
	d.WriteString("];\n")
	if err := os.WriteFile(dartOut, []byte(d.String()), 0o600); err != nil { //nolint:gosec // G703: the developer names the output.
		return fmt.Errorf("write %s: %w", dartOut, err)
	}
	return nil
}

// dartString quotes s as a Dart single-quoted string literal.
func dartString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `'`, `\'`, `$`, `\$`, "\n", `\n`)
	return "'" + r.Replace(s) + "'"
}

// dartDouble writes v as a Dart double literal.
func dartDouble(v float64) string {
	s := strconv.FormatFloat(v, 'f', -1, 64)
	if !strings.Contains(s, ".") {
		s += ".0"
	}
	return s
}
