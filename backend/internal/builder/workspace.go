package builder

import (
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// The files and directories of a build workspace (E5).
const (
	sdkDir     = "plux-fn"
	moduleDir  = "plux-module"
	vendorDir  = "vendor"
	moduleName = "plux-module"
)

// rootManifest is the manifest of the generated workspace: the members, the
// patch that resolves the unpublished `plux-fn` to the pinned SDK copy, and the
// release profile that is part of the reproducible-build contract (E7, FN-019).
func rootManifest(funcs []preparedFunction) []byte {
	var b strings.Builder
	b.WriteString("# Generated by the Plux builder (ADR-0063). Do not edit.\n\n")
	b.WriteString("[workspace]\nresolver = \"3\"\nmembers = [\n")
	fmt.Fprintf(&b, "    %q,\n", sdkDir)
	for _, f := range funcs {
		fmt.Fprintf(&b, "    %q,\n", f.dir())
	}
	fmt.Fprintf(&b, "    %q,\n]\n\n", moduleDir)
	b.WriteString("[patch.crates-io]\nplux-fn = { path = \"plux-fn\" }\n\n")
	b.WriteString("[profile.release]\nopt-level = \"s\"\nlto = true\ncodegen-units = 1\npanic = \"abort\"\nstrip = true\n")
	return []byte(b.String())
}

// cargoConfig replaces crates.io by the merged vendor directory, so resolution
// and building can only see vendored crates (FN-003, FN-016).
func cargoConfig() []byte {
	return []byte(`# Generated by the Plux builder (ADR-0063). Do not edit.

[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"
`)
}

// moduleManifest is the manifest of the generated wrapper crate: a cdylib that
// depends on every function crate by path (E5). The feature plux-schema makes
// the module export its schemas (FN-004).
func moduleManifest(funcs []preparedFunction) []byte {
	var b strings.Builder
	b.WriteString("# Generated by the Plux builder (ADR-0063). Do not edit.\n\n")
	b.WriteString("[package]\nname = \"" + moduleName + "\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n")
	b.WriteString("[lib]\ncrate-type = [\"cdylib\"]\n\n")
	b.WriteString("[dependencies]\nplux-fn = \"0.1\"\n")
	for _, f := range funcs {
		fmt.Fprintf(&b, "%s = { path = %q }\n", f.pkg, "../"+f.dir())
	}
	b.WriteString("\n[features]\nplux-schema = []\n")
	return []byte(b.String())
}

// moduleSource is the wrapper's lib.rs: one plux_fn::module! invocation with
// the functions sorted by name, so a function's index is its position (E5).
// The macro asserts every crate's placement against its document (PLX-7205).
func moduleSource(funcs []preparedFunction) []byte {
	entries := make([]string, len(funcs))
	for i, f := range funcs {
		entries[i] = f.ident + ": " + string(f.Placement)
	}
	return []byte("// Generated by the Plux builder (ADR-0063). Do not edit.\n\nplux_fn::module!(" +
		strings.Join(entries, ", ") + ");\n")
}

// toolchainFile pins the toolchain for developers who run cargo in a kept
// workspace (FN-001).
func toolchainFile() []byte {
	return []byte("[toolchain]\nchannel = \"" + RustVersion + "\"\n")
}

// generatedFiles returns the files the builder writes itself, by workspace path.
func generatedFiles(funcs []preparedFunction) map[string][]byte {
	return map[string][]byte{
		"Cargo.toml":              rootManifest(funcs),
		".cargo/config.toml":      cargoConfig(),
		"rust-toolchain.toml":     toolchainFile(),
		moduleDir + "/Cargo.toml": moduleManifest(funcs),
		moduleDir + "/src/lib.rs": moduleSource(funcs),
	}
}

// writeWorkspaceFile writes data below root, creating directories.
func writeWorkspaceFile(root, rel string, data []byte) error {
	dst := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(dst), 0o750); err != nil {
		return fmt.Errorf("builder.writeWorkspaceFile: %w", err)
	}
	if err := os.WriteFile(dst, data, 0o600); err != nil {
		return fmt.Errorf("builder.writeWorkspaceFile: %w", err)
	}
	return nil
}

// stagedHashes are the digests of everything copied into the workspace.
type stagedHashes struct {
	source, sdk string
}

// stageWorkspace writes the whole build workspace below root and returns the
// hashes of its inputs. The sources are copied function by function; their
// vendor directories are merged into one (FN-003).
func stageWorkspace(root string, sdk fs.FS, funcs []preparedFunction, budget int64) (stagedHashes, error) {
	for rel, data := range generatedFiles(funcs) {
		if err := writeWorkspaceFile(root, rel, data); err != nil {
			return stagedHashes{}, err
		}
	}
	sdkSum, err := stageSDK(root, sdk)
	if err != nil {
		return stagedHashes{}, err
	}
	owner, err := mergeVendorPlan(funcs)
	if err != nil {
		return stagedHashes{}, err
	}
	b := &sizeBudget{remaining: budget}
	var all []fileHash
	for i, f := range funcs {
		hashes, err := stageFunction(root, f, i, owner, b)
		if err != nil {
			return stagedHashes{}, err
		}
		all = append(all, hashes...)
	}
	return stagedHashes{source: canonicalHash(all), sdk: sdkSum}, nil
}

// stageSDK copies the pinned SDK crate (its manifest and sources) and returns
// its digest.
func stageSDK(root string, sdk fs.FS) (string, error) {
	var hashes []fileHash
	err := walkFiles(sdk, nil, func(rel string, data []byte) error {
		if rel != "Cargo.toml" && !strings.HasPrefix(rel, "src/") {
			return nil
		}
		hashes = append(hashes, fileHash{path: sdkDir + "/" + rel, sum: hexSum(data)})
		return writeWorkspaceFile(root, sdkDir+"/"+rel, data)
	})
	if err != nil {
		return "", fmt.Errorf("builder.stageSDK: %w", err)
	}
	if len(hashes) == 0 {
		return "", sourceError("the SDK directory holds no crate")
	}
	return canonicalHash(hashes), nil
}

// stageFunction copies one function crate and its vendored crates.
func stageFunction(root string, f preparedFunction, index int, owner map[string]int, b *sizeBudget) ([]fileHash, error) {
	merged := map[string]vendorCrate{}
	for _, c := range f.vendor {
		merged[c.topDir] = c
	}
	var hashes []fileHash
	err := walkFiles(f.Files, b, func(rel string, data []byte) error {
		hashes = append(hashes, fileHash{path: f.Name + "/" + rel, sum: hexSum(data)})
		dst := path.Join(f.dir(), rel)
		if inner, isVendor := strings.CutPrefix(rel, vendorDir+"/"); isVendor {
			top, rest, nested := strings.Cut(inner, "/")
			c, known := merged[top]
			if !nested || !known || owner[c.key()] != index {
				return nil
			}
			dst = path.Join(vendorDir, c.key(), rest)
		}
		return writeWorkspaceFile(root, dst, data)
	})
	if err != nil {
		return nil, fmt.Errorf("builder.stageFunction %s: %w", f.Name, err)
	}
	return hashes, nil
}
