export interface PathData {
  readonly d: string;
  readonly faded: boolean;
}

/** Extracts the `<path>` elements of one duotone SVG; the 20 % layer carries `opacity="0.2"`. */
export function parsePaths(svg: string): PathData[] {
  const paths: PathData[] = [];
  for (const match of svg.matchAll(/<path\s+([^>]*?)\/>/g)) {
    const attrs = match[1] ?? "";
    const d = /\bd="([^"]+)"/.exec(attrs)?.[1];
    if (d === undefined) {
      throw new Error(`path without d in: ${svg.slice(0, 80)}`);
    }
    paths.push({ d, faded: /opacity="0\.2"/.test(attrs) });
  }
  if (paths.length === 0) {
    throw new Error("svg without paths");
  }
  return paths;
}

export function render(read: (name: string) => string): string {
  const lines = [
    "// SPDX-FileCopyrightText: 2026 Plux contributors",
    "// SPDX-License-Identifier: AGPL-3.0-only",
    "//",
    "// Generated by scripts/gen-icons.ts (make studio-gen-icons). Do not edit.",
    "// Icon paths: Phosphor Icons, MIT licence, Copyright (c) 2023 Phosphor Icons (@phosphor-icons/core 2.1.1).",
    "",
    "export const iconNames = [",
    ...iconNames.map((n) => `  ${JSON.stringify(n)},`),
    "] as const;",
    "",
    "export type IconName = (typeof iconNames)[number];",
    "",
    "export interface IconPath {",
    "  readonly d: string;",
    "  /** The 20 % fill layer of the duotone weight. */",
    "  readonly faded: boolean;",
    "}",
    "",
    "export const iconPaths: Readonly<Record<IconName, readonly IconPath[]>> = {",
  ];
  for (const name of iconNames) {
    lines.push(`  ${JSON.stringify(name)}: [`);
    for (const p of parsePaths(read(name))) {
      lines.push(`    { d: ${JSON.stringify(p.d)}, faded: ${p.faded} },`);
    }
    lines.push("  ],");
  }
  lines.push("};", "");
  return lines.join("\n");
}

if (import.meta.main) {
  const here = dirname(fileURLToPath(import.meta.url));
  const assets = join(here, "..", "node_modules", "@phosphor-icons", "core", "assets", "duotone");
  const out = render((name) => readFileSync(join(assets, `${name}-duotone.svg`), "utf8"));
  writeFileSync(join(here, "..", "src", "icons.gen.ts"), out);
}
